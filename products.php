<?php
/* ============================================================
   Product Manager API  (koi database nahi — simple JSON file)
   GET  ?action=ping                 -> server hai ya nahi + products
   GET  ?action=list                 -> saare products
   POST ?action=save   {token,products:[...]}
   POST ?action=upload {token,name,data:"data:image/jpeg;base64,..."}
   ============================================================ */
header("Content-Type: application/json; charset=utf-8");
header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Headers: Content-Type");
if ($_SERVER["REQUEST_METHOD"] === "OPTIONS") { http_response_code(204); exit; }

$CFG = require __DIR__ . "/config.php";
$action = $_GET["action"] ?? "ping";

function readProducts($f){
  if (!file_exists($f)) return [];
  $j = @json_decode(file_get_contents($f), true);
  return is_array($j) ? $j : [];
}
function tokenOk($CFG, $in){
  return isset($in["token"]) && is_string($in["token"]) && hash_equals($CFG["token"], $in["token"]);
}

/* ---------- PING / LIST ---------- */
if ($action === "ping" || $action === "list") {
  echo json_encode(["ok" => true, "mode" => $action, "count" => count(readProducts($CFG["json"])),
                    "products" => readProducts($CFG["json"])]);
  exit;
}

/* ---------- body ---------- */
$raw  = file_get_contents("php://input");
$in   = json_decode($raw, true);
if (!is_array($in)) { http_response_code(400); echo json_encode(["ok"=>false,"error"=>"bad json"]); exit; }
if (!tokenOk($CFG, $in)) { http_response_code(403); echo json_encode(["ok"=>false,"error"=>"galat token"]); exit; }

/* ---------- SAVE ---------- */
if ($action === "save") {
  if (!isset($in["products"]) || !is_array($in["products"])) {
    http_response_code(400); echo json_encode(["ok"=>false,"error"=>"products missing"]); exit;
  }
  $all = $in["products"];
  // basic sanity + ids unique
  $seen = []; $clean = [];
  foreach ($all as $p) {
    if (!is_array($p) || empty($p["id"])) continue;
    if (isset($seen[$p["id"]])) continue;
    $seen[$p["id"]] = 1;
    $p["price"] = (int)($p["price"] ?? 0);
    $p["mrp"]   = (int)($p["mrp"] ?? $p["price"]);
    $p["wt"]    = (int)($p["wt"] ?? 250);
    $clean[] = $p;
  }
  $pretty = json_encode($clean, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
  @mkdir(dirname($CFG["json"]), 0775, true);
  if (@file_put_contents($CFG["json"], $pretty) === false) {
    http_response_code(500); echo json_encode(["ok"=>false,"error"=>"data/products.json likh nahi saka — folder permission 755/775 dein"]); exit;
  }
  $live = [];
  foreach ($clean as $p) {
    if (array_key_exists("active", $p) && $p["active"] === false) continue;
    $live[] = $p;
  }
  $js = "/* AUTO-GENERATED by Product Manager — " . date("d-m-Y H:i") . " — haath se mat badlo. */\n"
      . "window.__LIVE_PRODUCTS = " . json_encode($live, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . ";\n";
  @file_put_contents($CFG["livejs"], $js);
  echo json_encode(["ok"=>true, "saved"=>count($clean), "live"=>count($live)]);
  exit;
}

/* ---------- IMAGE UPLOAD ---------- */
if ($action === "upload") {
  if (empty($in["data"])) { http_response_code(400); echo json_encode(["ok"=>false,"error"=>"no data"]); exit; }
  if (!preg_match('/^data:image\/(jpeg|png|jpg|webp);base64,/', $in["data"], $m)) {
    http_response_code(400); echo json_encode(["ok"=>false,"error"=>"sirf image allowed"]); exit;
  }
  $bin = base64_decode(substr($in["data"], strpos($in["data"], ",") + 1), true);
  if ($bin === false || strlen($bin) > 6 * 1024 * 1024) {
    http_response_code(400); echo json_encode(["ok"=>false,"error"=>"image badi ya kharab hai (max 6 MB)"]); exit;
  }
  @mkdir($CFG["uploaddir"], 0775, true);
  $ext  = $m[1] === "png" ? "png" : ($m[1] === "webp" ? "webp" : "jpg");
  $base = preg_replace('/[^a-z0-9]+/i', "-", strtolower(pathinfo((string)($in["name"] ?? "img"), PATHINFO_FILENAME)));
  $base = trim($base, "-") ?: "img";
  $file = $base . "-" . substr(md5($bin . microtime(true)), 0, 6) . "." . $ext;
  if (@file_put_contents($CFG["uploaddir"] . $file, $bin) === false) {
    http_response_code(500); echo json_encode(["ok"=>false,"error"=>"upload folder likh nahi saka — permission 775 dein"]); exit;
  }
  echo json_encode(["ok"=>true, "path"=>$CFG["uploadurl"] . $file, "bytes"=>strlen($bin)]);
  exit;
}

http_response_code(404);
echo json_encode(["ok"=>false,"error"=>"unknown action"]);
